-- Section 3 — Row-Level Security
-- Isolation is enforced by PostgreSQL Row-Level Security. Each organizational table restricts every row to the current tenant and scenario, read from the session variables app.tenant_id and app.scenario_id set with SET LOCAL at the start of each transaction. The two global catalogues carry no tenant or scenario and are exempt. The application role must not hold BYPASSRLS.
ALTER TABLE TENANT ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_scenario_isolation ON TENANT
    USING (TENANT_ID = current_setting('app.tenant_id')::bigint
       AND SCENARIO_ID = current_setting('app.scenario_id')::bigint);

