-- 3D.DET
-- Data Definition Language (DDL)
-- PostgreSQL
-- 108 tables · Row-Level Security · executable schema
-- Overview
-- This document is the executable PostgreSQL schema of the 3D.DET data model.
-- It contains the table definitions, the indexes, and the Row-Level Security policies that enforce tenant and scenario isolation. Field-level descriptions and the rationale for the model are in document 01.4 — DB MODEL. Table blocks are listed in numbering order for reference; execution requires dependency order (forward references exist, e.g. ASSESSMENT_RECORD before LMS_RUBRIC in numbering but after it in execution).
-- Every organizational table carries TENANT_ID and SCENARIO_ID as leading context columns. SCENARIO 0 is the real organization (AS-IS); SCENARIO 1, 2, 3… are redesign projects (TO-BE). The two global catalogues (NODE_TYPE_CATALOG, PATHOLOGY_MASTER) carry neither column.
