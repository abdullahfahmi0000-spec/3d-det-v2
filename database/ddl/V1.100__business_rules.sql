-- 56. BUSINESS_RULE_MASTER
CREATE TABLE BUSINESS_RULE_MASTER (
    RULE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RULE_CODE VARCHAR(80) NOT NULL,
    RULE_NAME VARCHAR(255) NOT NULL,
    RULE_TYPE VARCHAR(15) CHECK (RULE_TYPE IN ('Authorization','Pricing','Eligibility','Threshold','Workflow','Compliance','Calculation','Scoring','Routing')) NOT NULL,
    DESCRIPTION TEXT,
    REGULATORY_BASIS VARCHAR(500),
    CRITICALITY VARCHAR(10) CHECK (CRITICALITY IN ('Low','Medium','High','Critical')) NOT NULL DEFAULT 'Medium',
    STATUS VARCHAR(14) CHECK (STATUS IN ('Draft','Active','Under_Review','Deprecated')) NOT NULL DEFAULT 'Draft',
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    VERSION VARCHAR(20) NOT NULL DEFAULT '1.0',
    SUPERSEDES_RULE_ID BIGINT,
    DELIBERATION_REFERENCE VARCHAR(500),
    OWNER_NODE_ID BIGINT NOT NULL,
    AUTOMATED BOOLEAN NOT NULL DEFAULT FALSE,
    SYSTEM_REFERENCE VARCHAR(255),
    COMPLIANCE_RELEVANT BOOLEAN NOT NULL DEFAULT FALSE,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    MODIFIED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY BIGINT,
    MODIFIED_BY BIGINT,
    CONSTRAINT uk_rule_code_tenant UNIQUE (TENANT_ID, SCENARIO_ID, RULE_CODE, VERSION)
);

-- 57. BUSINESS_RULE_PARAMETER
CREATE TABLE BUSINESS_RULE_PARAMETER (
    PARAM_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RULE_ID BIGINT NOT NULL,
    PARAM_CODE VARCHAR(80) NOT NULL,
    PARAM_NAME VARCHAR(255) NOT NULL,
    PARAM_TYPE VARCHAR(13) CHECK (PARAM_TYPE IN ('Numeric','Threshold','Boolean','Categorical','Date_Range','List','Percentage')) NOT NULL,
    CURRENT_VALUE VARCHAR(500) NOT NULL,
    MIN_ALLOWED DECIMAL(18,4),
    MAX_ALLOWED DECIMAL(18,4),
    UNIT VARCHAR(20),
    ALLOWED_VALUES_JSON JSONB,
    SOURCE VARCHAR(23) CHECK (SOURCE IN ('System_Configuration','Manual_Declaration','CdA_Resolution','Regulatory_Imposition','Estimated')) NOT NULL,
    LAST_VERIFIED_AT TIMESTAMP,
    LAST_VERIFIED_BY BIGINT,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0
);

-- 58. TASK_BUSINESS_RULE
