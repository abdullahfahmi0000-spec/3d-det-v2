-- 79. STANDING_APPROVAL
CREATE TABLE STANDING_APPROVAL (
    STANDING_APPROVAL_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    APPROVAL_CODE VARCHAR(50) NOT NULL,
    APPROVER_PERSON_ID BIGINT NULL,
    TASK_ID BIGINT NOT NULL,
    PROCESS_ID BIGINT NOT NULL,
    BUSINESS_RULE_ID BIGINT NULL,
    COMMITMENT_TYPE_ID BIGINT NULL,
    THRESHOLD_AMOUNT DECIMAL(18,2) NULL,
    CURRENCY_CODE CHAR(3) NULL,
    REQUIRED_CONTROLS TEXT,
    PROCESS_VERSION_REF VARCHAR(20) NOT NULL,
    RULE_VERSION_REF VARCHAR(20) NULL,
    MATURITY_STAGE VARCHAR(10) CHECK (MATURITY_STAGE IN ('Sign_All','Sample','Standing')) NOT NULL DEFAULT 'Sign_All',
    SAMPLE_PCT DECIMAL(5,2) NULL,
    ATTESTATION_FREQUENCY VARCHAR(13) CHECK (ATTESTATION_FREQUENCY IN ('Monthly','Quarterly','Semi_Annual')) NOT NULL DEFAULT 'Quarterly',
    EXCEPTION_RATE_THRESHOLD_PCT DECIMAL(5,2) NOT NULL DEFAULT 5.00,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE NOT NULL,
    STATUS VARCHAR(11) CHECK (STATUS IN ('Draft','Active','Suspended','Expired','Revoked')) NOT NULL DEFAULT 'Draft',
    SUSPENSION_REASON VARCHAR(20) CHECK (SUSPENSION_REASON IN ('Exception_Rate','Version_Change','Missed_Attestation','Manual')) NULL,
    SUSPENDED_AT TIMESTAMP NULL,
    GRANTED_AT TIMESTAMP NULL,
    REVOKED_AT TIMESTAMP NULL,
    NOTES TEXT,
    APPROVER_NODE_ID BIGINT NULL,
    CONSTRAINT uk_sa_code_tenant UNIQUE (APPROVAL_CODE, TENANT_ID, SCENARIO_ID),
    CONSTRAINT chk_sa_expiry CHECK (VALID_TO <= VALID_FROM + INTERVAL '12 months'),
    CONSTRAINT chk_sa_window CHECK (VALID_TO > VALID_FROM),
    CONSTRAINT chk_sa_sample CHECK (MATURITY_STAGE <> 'Sample' OR SAMPLE_PCT IS NOT NULL),
    CONSTRAINT chk_sa_suspended CHECK (STATUS <> 'Suspended' OR SUSPENSION_REASON IS NOT NULL),
    CONSTRAINT chk_sa_approver_xor CHECK (
        (APPROVER_PERSON_ID IS NOT NULL) <> (APPROVER_NODE_ID IS NOT NULL))
);

-- 80. APPROVAL_ATTESTATION
CREATE TABLE APPROVAL_ATTESTATION (
    ATTESTATION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    STANDING_APPROVAL_ID BIGINT NOT NULL,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    PERIOD_START DATE NOT NULL,
    PERIOD_END DATE NOT NULL,
    INSTANCES_COVERED INT NOT NULL DEFAULT 0,
    EXCEPTIONS_COUNT INT NOT NULL DEFAULT 0,
    EXCEPTION_RATE_PCT DECIMAL(5,2) NULL,
    SAMPLE_SIZE INT NOT NULL DEFAULT 0,
    SAMPLE_FINDINGS TEXT,
    OUTCOME VARCHAR(10) CHECK (OUTCOME IN ('Clean','Findings','Failed')) NULL,
    SIGNED_BY_PERSON_ID BIGINT NULL,
    SIGNED_AT TIMESTAMP NULL,
    NOTES TEXT,
    CONSTRAINT uk_att_period UNIQUE (STANDING_APPROVAL_ID, PERIOD_START),
    CONSTRAINT chk_att_period CHECK (PERIOD_END > PERIOD_START),
    CONSTRAINT chk_att_signed CHECK (OUTCOME IS NULL OR SIGNED_BY_PERSON_ID IS NOT NULL)
);
