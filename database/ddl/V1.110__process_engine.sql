-- 62. DELEGATION_OF_AUTHORITY
CREATE TABLE DELEGATION_OF_AUTHORITY (
    DOA_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    SUBJECT_TYPE VARCHAR(10) CHECK (SUBJECT_TYPE IN ('Person','AI_Agent')) NOT NULL,
    PERSON_ID BIGINT,
    AI_AGENT_REFERENCE VARCHAR(255),
    COMMITMENT_TYPE_ID BIGINT NOT NULL,
    THRESHOLD_AMOUNT DECIMAL(18,2) NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    GRANTED_BY_PERSON_ID BIGINT,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    NOTES TEXT,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    APPROVAL_SCOPE VARCHAR(14) CHECK (APPROVAL_SCOPE IN ('Per_Instance','Population')) NOT NULL DEFAULT 'Per_Instance',
    RULE_CONSTRAINT_ID BIGINT NULL,
    SOURCE_NODE_ID BIGINT NULL,
    DEROGATION_TYPE VARCHAR(18) CHECK (DEROGATION_TYPE IN ('Within_Policy','Reduction','Derogation_Above','Standalone'))
        NOT NULL DEFAULT 'Standalone',
    CONSTRAINT uk_doa UNIQUE (SUBJECT_TYPE, PERSON_ID, AI_AGENT_REFERENCE, COMMITMENT_TYPE_ID, VALID_FROM, TENANT_ID, SCENARIO_ID),
    CONSTRAINT chk_doa_subject CHECK ( (SUBJECT_TYPE='Person' AND PERSON_ID IS NOT NULL AND AI_AGENT_REFERENCE IS NULL) OR (SUBJECT_TYPE='AI_Agent' AND PERSON_ID IS NULL AND AI_AGENT_REFERENCE IS NOT NULL)),
    CONSTRAINT chk_doa_derogation CHECK (
        DEROGATION_TYPE <> 'Derogation_Above' OR
        (GRANTED_BY_PERSON_ID IS NOT NULL AND VALID_TO IS NOT NULL)),
    CONSTRAINT chk_doa_derived CHECK (
        DEROGATION_TYPE = 'Standalone' OR RULE_CONSTRAINT_ID IS NOT NULL)
);

-- 63. ESCALATION_RULE
CREATE TABLE ESCALATION_RULE (
    RULE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    FLOW_ID BIGINT NOT NULL,
    TRIGGER_TYPE VARCHAR(15) CHECK (TRIGGER_TYPE IN ('DoA_Threshold','Timeout','Manual')) NOT NULL,
    COMMITMENT_TYPE_ID BIGINT,
    APPROVER_RESOLUTION VARCHAR(18) CHECK (APPROVER_RESOLUTION IN ('DoA_Chain','Fixed_Person','RACI_Accountable')) NOT NULL DEFAULT 'DoA_Chain',
    FIXED_APPROVER_PERSON_ID BIGINT,
    APPROVAL_TASK_NAME VARCHAR(255) NOT NULL,
    ON_REJECTED_FLOW_ID BIGINT,
    FIRST_REMINDER_HOURS INT NOT NULL DEFAULT 24,
    REMINDER_INTERVAL_HOURS INT NOT NULL DEFAULT 24,
    MAX_REMINDERS_BEFORE_LEVEL_ESC INT NOT NULL DEFAULT 3,
    MAX_ESCALATION_LEVELS INT NOT NULL DEFAULT 3,
    ACTIVE BOOLEAN DEFAULT TRUE,
    ESCALATION_RESOLUTION_TYPE VARCHAR(16) CHECK (ESCALATION_RESOLUTION_TYPE IN ('Hierarchical','Collegial_Body'))
        NOT NULL DEFAULT 'Hierarchical',
    COLLEGIAL_BODY_ID BIGINT NULL,
    MAX_SESSIONS_BEFORE_ESC INT NULL,
    CONSTRAINT chk_esc_collegial CHECK (
        ESCALATION_RESOLUTION_TYPE <> 'Collegial_Body' OR
        (COLLEGIAL_BODY_ID IS NOT NULL AND MAX_SESSIONS_BEFORE_ESC IS NOT NULL))
);

