-- 48. JOB_AUTOMATION_SNAPSHOT
CREATE TABLE JOB_AUTOMATION_SNAPSHOT (
    SNAPSHOT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    JOB_NODE_ID BIGINT NOT NULL,
    SNAPSHOT_DATE DATE NOT NULL,
    EXECUTION_MODE VARCHAR(10) CHECK (EXECUTION_MODE IN ('Human','Hybrid','Agentic')) NOT NULL,
