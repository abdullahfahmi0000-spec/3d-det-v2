    AGENTIC_PCT DECIMAL(5,2),
    HUMAN_ACCOUNTABILITY_RESIDUAL_PCT DECIMAL(5,2),
    TASKS_TOTAL INT,
    TASKS_AGENTIC INT,
    CALCULATED_FROM_SOURCE VARCHAR(18) CHECK (CALCULATED_FROM_SOURCE IN ('JOB_TASK_RACI','PERSON_TASK_RACI')) DEFAULT 'JOB_TASK_RACI',
    CONSTRAINT uk_snapshot UNIQUE (TENANT_ID, SCENARIO_ID, JOB_NODE_ID, SNAPSHOT_DATE)
);

