-- 11. PERMISSION
CREATE TABLE PERMISSION (
    PERMISSION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    PERSON_ID BIGINT NULL,
    AGENT_ID BIGINT NULL,
    PROFILE_ID BIGINT NULL,
    RESOURCE_TYPE VARCHAR(17) CHECK (RESOURCE_TYPE IN ('BOM','FIELD','SUBTREE','NODE_TYPE','OPERATION','INITIATIVE','TASK','PATHOLOGY','CONSULTING_NOTE')) NOT NULL,
    RESOURCE_CATEGORY VARCHAR(16) CHECK (RESOURCE_CATEGORY IN ('ORGANIZATIONAL','DIAGNOSTIC','PROCESS','INITIATIVE','SYSTEM')) GENERATED ALWAYS AS (CASE WHEN RESOURCE_TYPE IN ('BOM','FIELD','SUBTREE') THEN 'ORGANIZATIONAL' WHEN RESOURCE_TYPE IN ('PATHOLOGY','CONSULTING_NOTE') THEN 'DIAGNOSTIC' WHEN RESOURCE_TYPE = 'TASK' THEN 'PROCESS' WHEN RESOURCE_TYPE = 'INITIATIVE' THEN 'INITIATIVE' ELSE 'SYSTEM' END) STORED,
    RESOURCE_REF VARCHAR(255) NOT NULL,
    ACTION VARCHAR(10) CHECK (ACTION IN ('VIEW','EDIT','INSERT','DELETE','APPROVE','OWN')) NOT NULL,
    GRANT_OR_DENY VARCHAR(10) CHECK (GRANT_OR_DENY IN ('GRANT','DENY')) NOT NULL DEFAULT 'GRANT',
    SCOPE_FILTER JSONB,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    GRANTED_BY BIGINT,
    GRANT_REASON TEXT,
    CONSTRAINT chk_perm_subject CHECK ( ((PERSON_ID IS NOT NULL)::int + (AGENT_ID IS NOT NULL)::int + (PROFILE_ID IS NOT NULL)::int) = 1 )
);

