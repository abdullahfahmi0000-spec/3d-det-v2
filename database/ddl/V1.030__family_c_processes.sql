    OUTCOME VARCHAR(11) CHECK (OUTCOME IN ('Success','Rejected','Cancelled','Escalated')),
    TOTAL_DURATION_MINUTES INT,
    INVOLVED_PERSON_IDS JSONB,
    FINANCIAL_IMPACT DECIMAL(18,2),
    CONTEXT_DATA JSONB,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_instance_code_tenant UNIQUE (INSTANCE_CODE, TENANT_ID, SCENARIO_ID)
);

-- 18. PROCESS_INSTANCE_EVENT
CREATE TABLE PROCESS_INSTANCE_EVENT (
    EVENT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    INSTANCE_ID BIGINT NOT NULL,
    FLOW_ID BIGINT NULL,
    GATEWAY_ID BIGINT NULL,
    EVENT_TYPE VARCHAR(23) CHECK (EVENT_TYPE IN ('Started','Completed','Suspended','Resumed','Failed','Skipped','Escalated','Branch_Activated','Reminder_Sent','Approval_Requested','Approval_Granted','Approval_Rejected','Quorum_Not_Reached','Deliberation_Deferred')) NOT NULL,
    EVENT_TIMESTAMP TIMESTAMP NOT NULL,
    PERFORMED_BY_PERSON_ID BIGINT,
    PERFORMED_BY_AI_AGENT BOOLEAN DEFAULT FALSE,
    AI_AGENT_REFERENCE VARCHAR(255),
    DURATION_MINUTES INT,
    WAIT_BEFORE_MINUTES INT,
    OUTCOME_LABEL VARCHAR(100),
    NOTES TEXT,
    SOURCE_SYSTEM VARCHAR(50),
    RAW_DATA_JSON JSONB,
    STANDING_APPROVAL_ID BIGINT NULL,
    DECISION_RECORD_ID BIGINT NULL,
    CONSTRAINT chk_pie_scope CHECK (
        (FLOW_ID IS NOT NULL AND GATEWAY_ID IS NULL) OR
        (FLOW_ID IS NULL     AND GATEWAY_ID IS NOT NULL))
);
