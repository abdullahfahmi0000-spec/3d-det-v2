-- 14. PROCESS_MASTER
CREATE TABLE PROCESS_MASTER (
    PROCESS_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PROCESS_CODE VARCHAR(50) NOT NULL,
    PROCESS_NAME VARCHAR(255) NOT NULL,
    DESCRIPTION TEXT,
    APQC_REFERENCE VARCHAR(20),
    PROCESS_CATEGORY_ID BIGINT NOT NULL,
    TRIGGER_TYPE_ID BIGINT NOT NULL,
    TRIGGER_DESCRIPTION TEXT,
    END_CONDITION TEXT,
    OWNER_PERSON_ID BIGINT,
    CRITICALITY VARCHAR(10) CHECK (CRITICALITY IN ('Low','Medium','High','Critical')) DEFAULT 'Medium',
    AVERAGE_DURATION_DAYS DECIMAL(8,2),
    AVERAGE_FREQUENCY_PER_YEAR INT,
    COMPLIANCE_RELEVANT BOOLEAN DEFAULT FALSE,
    PRODUCTION_MODE VARCHAR(16) CHECK (PRODUCTION_MODE IN ('MTO','ETO','ATO','Repetitive','Continuous','Project','Hybrid','Not_Applicable')) NULL,
    BPMN_XML_REF VARCHAR(255),
    STATUS VARCHAR(14) CHECK (STATUS IN ('Draft','Active','Deprecated','Under_Review')) DEFAULT 'Draft',
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    VERSION VARCHAR(20),
    PARENT_PROCESS_ID BIGINT,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    RACI_VALIDATION_STATUS VARCHAR(13) CHECK (RACI_VALIDATION_STATUS IN ('Not_Checked','Passed','Failed'))
        NOT NULL DEFAULT 'Not_Checked',
    RACI_VALIDATED_AT TIMESTAMP NULL,
    STEPS_UNRESOLVED_COUNT INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_process_code_tenant UNIQUE (PROCESS_CODE, TENANT_ID, SCENARIO_ID),
    CONSTRAINT chk_process_publish CHECK (
        STATUS <> 'Active' OR
        (RACI_VALIDATION_STATUS = 'Passed' AND STEPS_UNRESOLVED_COUNT = 0))
);

-- 15. PROCESS_TASK_FLOW
CREATE TABLE PROCESS_TASK_FLOW (
    FLOW_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    PROCESS_ID BIGINT NOT NULL,
    TASK_ID BIGINT NULL,
    STEP_TYPE VARCHAR(14) CHECK (STEP_TYPE IN ('Task','Call_Process')) NOT NULL DEFAULT 'Task',
    CALLED_PROCESS_ID BIGINT NULL,
    CALL_MODE VARCHAR(10) CHECK (CALL_MODE IN ('Sync','Async')) NULL,
    STEP_NUMBER INT NOT NULL,
    STEP_NAME VARCHAR(255),
    IS_START BOOLEAN DEFAULT FALSE,
    IS_END BOOLEAN DEFAULT FALSE,
    NEXT_FLOW_ID BIGINT,
    GATEWAY_ID BIGINT,
    EXPECTED_DURATION_MINUTES INT,
    EXPECTED_WAIT_BEFORE_MINUTES INT,
    SLA_DURATION_MINUTES INT,
    EXECUTION_MODE VARCHAR(13) CHECK (EXECUTION_MODE IN ('Mandatory','Optional','Conditional','Parallel')) DEFAULT 'Mandatory',
    AUTOMATION_CURRENT_PCT DECIMAL(5,2) DEFAULT 0,
    AUTOMATION_TARGET_PCT DECIMAL(5,2) DEFAULT 0,
    LOCATION_HINT VARCHAR(255),
    NOTES TEXT,
    CONSTRAINT uk_flow_step UNIQUE (PROCESS_ID, STEP_NUMBER),
    CONSTRAINT chk_flow_type CHECK (
        (STEP_TYPE='Task'         AND TASK_ID IS NOT NULL AND CALLED_PROCESS_ID IS NULL) OR
        (STEP_TYPE='Call_Process' AND TASK_ID IS NULL     AND CALLED_PROCESS_ID IS NOT NULL))
);

-- 16. PROCESS_GATEWAY
CREATE TABLE PROCESS_GATEWAY (
