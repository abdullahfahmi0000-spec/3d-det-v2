-- 17. PROCESS_INSTANCE
CREATE TABLE PROCESS_INSTANCE (
    INSTANCE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    INSTANCE_CODE VARCHAR(50) NOT NULL,
    PROCESS_ID BIGINT NOT NULL,
    PROCESS_VERSION VARCHAR(20),
    EXTERNAL_REFERENCE VARCHAR(255),
    VARIANT_LABEL VARCHAR(255) NULL,
    PARENT_INSTANCE_ID BIGINT NULL,
    CALLING_FLOW_ID BIGINT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    ENDED_AT TIMESTAMP,
    CURRENT_FLOW_ID BIGINT,
