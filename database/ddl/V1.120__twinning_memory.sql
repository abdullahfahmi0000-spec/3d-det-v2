-- 69. TWIN_OBSERVATION
CREATE TABLE TWIN_OBSERVATION (
    OBSERVATION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    PERSON_ID BIGINT NOT NULL,
    HOLDS_POSITION_ID BIGINT NULL,
    JOB_NODE_ID BIGINT NULL,
    CANDIDATE_TASK_NAME VARCHAR(255) NOT NULL,
    CANDIDATE_DESCRIPTION TEXT,
    SUGGESTED_TASK_FORMALITY VARCHAR(10) CHECK (SUGGESTED_TASK_FORMALITY IN ('Formal','Informal')) NOT NULL DEFAULT 'Informal',
    SOURCE_TYPES JSONB,
    SUGGESTED_TASK_CATEGORY_ID BIGINT NULL,
    OBSERVATION_PERIOD_FROM DATE NOT NULL,
    OBSERVATION_PERIOD_TO DATE NOT NULL,
    EVIDENCE_COUNT INT DEFAULT 0,
    ESTIMATED_OCCURRENCES_PER_YEAR DECIMAL(8,2),
    ESTIMATED_DURATION_MINUTES INT,
    CONFIDENCE_PCT DECIMAL(5,2),
    STATUS VARCHAR(12) CHECK (STATUS IN ('Captured','Proposed','Accepted','Rejected','Superseded'))
        NOT NULL DEFAULT 'Captured',
    PROPOSED_BY_AGENT_ID BIGINT NULL,
    PROPOSED_AT TIMESTAMP NULL,
    DECIDED_BY_PERSON_ID BIGINT NULL,
    DECIDED_AT TIMESTAMP NULL,
    DECISION_NOTES TEXT,
    PROMOTION_TARGET VARCHAR(10) CHECK (PROMOTION_TARGET IN ('JOB','PERSON')) NULL,
    PROMOTED_TASK_ID BIGINT NULL,
    PROMOTED_AT TIMESTAMP NULL,
    PEER_MATCH_COUNT INT DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_obs_promotion CHECK (STATUS <> 'Accepted' OR (PROMOTION_TARGET IS NOT NULL AND PROMOTED_TASK_ID IS NOT NULL)),
    CONSTRAINT chk_obs_period CHECK (OBSERVATION_PERIOD_TO >= OBSERVATION_PERIOD_FROM)
);

