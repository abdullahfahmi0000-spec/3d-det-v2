-- 19. PAEI_ASSESSMENT
CREATE TABLE PAEI_ASSESSMENT (
    ASSESSMENT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    TARGET_TYPE VARCHAR(10) CHECK (TARGET_TYPE IN ('PERSON','JOB','ROLE','UNIT')) NOT NULL,
    TARGET_ID BIGINT NOT NULL,
    ASSESSED_PAEI JSONB NOT NULL,
    ASSESSMENT_DATE DATE NOT NULL,
    ASSESSED_BY_PERSON_ID BIGINT NOT NULL,
    IS_BASELINE BOOLEAN DEFAULT FALSE,
    EVIDENCE_NOTES TEXT,
    CONFIDENCE_LEVEL VARCHAR(10) CHECK (CONFIDENCE_LEVEL IN ('High','Medium','Low')) DEFAULT 'Medium',
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    METHODOLOGY_REF VARCHAR(255),
    NOTES TEXT,
    CONSTRAINT uk_paei_logical UNIQUE (TARGET_TYPE, TARGET_ID, ASSESSMENT_DATE, IS_BASELINE)
);

-- 20. LIFECYCLE_ASSESSMENT
CREATE TABLE LIFECYCLE_ASSESSMENT (
    LC_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    NODE_ID BIGINT NOT NULL,
    ASSESSED_STAGE VARCHAR(15) CHECK (ASSESSED_STAGE IN ('Courtship','Infancy','Go-Go','Adolescence','Prime','Stable','Aristocracy','Recrimination','Bureaucracy','Death')) NOT NULL,
    ASSESSMENT_DATE DATE NOT NULL,
    ASSESSED_BY_PERSON_ID BIGINT NOT NULL,
    PAEI_OBSERVED_UNIT JSONB,
    EVIDENCE_NOTES TEXT,
    DIRECTION_TREND VARCHAR(13) CHECK (DIRECTION_TREND IN ('Stable','Progressing','Regressing')),
    NEXT_REVIEW_DATE DATE,
    CONFIDENCE_LEVEL VARCHAR(10) CHECK (CONFIDENCE_LEVEL IN ('High','Medium','Low')) DEFAULT 'Medium',
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    CONSTRAINT uk_lc_logical UNIQUE (NODE_ID, ASSESSMENT_DATE)
);

-- 21. PATHOLOGY_MASTER
CREATE TABLE PATHOLOGY_MASTER (
    PATHOLOGY_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PATHOLOGY_CODE VARCHAR(50) NOT NULL UNIQUE,
    PATHOLOGY_NAME VARCHAR(255) NOT NULL,
    DESCRIPTION TEXT,
    TYPICAL_LIFECYCLE_STAGE VARCHAR(15) CHECK (TYPICAL_LIFECYCLE_STAGE IN ('Courtship','Infancy','Go-Go','Adolescence','Prime','Stable','Aristocracy','Recrimination','Bureaucracy','Death')),
    SEVERITY_DEFAULT VARCHAR(10) CHECK (SEVERITY_DEFAULT IN ('Low','Medium','High','Critical')) DEFAULT 'Medium',
    TYPICAL_SYMPTOMS JSONB,
    TYPICAL_INTERVENTIONS JSONB,
    ADIZES_REFERENCE TEXT,
    MEDIA_REFERENCE JSONB,
    CREATED_BY_PERSON_ID BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR(14) CHECK (STATUS IN ('Active','Deprecated','Under_Review')) DEFAULT 'Active'
);

