-- 23. CONSULTING_NOTE
CREATE TABLE CONSULTING_NOTE (
    NOTE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    AUTHORED_BY_PERSON_ID BIGINT NOT NULL,
    NOTE_TYPE VARCHAR(16) CHECK (NOTE_TYPE IN ('OBSERVATION','DIAGNOSIS','RECOMMENDATION','FOLLOWUP','WARNING','CONTEXT')) NOT NULL,
    TARGET_TYPE VARCHAR(22) CHECK (TARGET_TYPE IN ('UNIT','INITIATIVE','PERSON','PATHOLOGY','LIFECYCLE_ASSESSMENT','PROCESS')) NOT NULL,
    TARGET_ID BIGINT NOT NULL,
    AUTHORING_DATE DATE NOT NULL,
    NOTE_TEXT TEXT NOT NULL,
