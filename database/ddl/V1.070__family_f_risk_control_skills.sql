-- 45. SKILL_MASTER
CREATE TABLE SKILL_MASTER (
    SKILL_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    TENANT_KEY BIGINT GENERATED ALWAYS AS (COALESCE(TENANT_ID,0)) STORED,
    SKILL_CODE VARCHAR(50) NOT NULL,
    SKILL_NAME VARCHAR(200) NOT NULL,
    SKILL_TYPE VARCHAR(15) CHECK (SKILL_TYPE IN ('Competence','Certification','License')) NOT NULL,
    IS_REGULATORY BOOLEAN DEFAULT FALSE,
    ISSUING_BODY VARCHAR(120),
    VALIDITY_MONTHS INT NULL,
    DESCRIPTION TEXT,
    STATUS VARCHAR(12) CHECK (STATUS IN ('Active','Deprecated')) DEFAULT 'Active',
    CONSTRAINT uk_skill UNIQUE (SKILL_CODE, TENANT_KEY)
);

-- 46. PERSON_SKILL
