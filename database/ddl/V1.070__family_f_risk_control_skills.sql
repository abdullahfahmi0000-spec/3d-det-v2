-- 40. RISK_MASTER
CREATE TABLE RISK_MASTER (
    RISK_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    PARENT_RISK_ID BIGINT NULL,
    RISK_CODE VARCHAR(50) NOT NULL,
    RISK_NAME VARCHAR(200) NOT NULL,
    RISK_CATEGORY VARCHAR(80),
    DESCRIPTION TEXT,
    INHERENT_LIKELIHOOD SMALLINT,
    INHERENT_IMPACT SMALLINT,
    INHERENT_SCORE DECIMAL(5,2),
    RISK_APPETITE VARCHAR(40),
    RISK_OWNER_JOB_ID BIGINT NULL,
    LINE_OF_DEFENSE VARCHAR(10) CHECK (LINE_OF_DEFENSE IN ('First','Second','Third')),
    REGULATORY_REFS JSONB,
    VALID_FROM DATE,
    VALID_TO DATE,
    STATUS VARCHAR(14) CHECK (STATUS IN ('Active','Deprecated','Under_Review')) DEFAULT 'Active',
    CONSTRAINT uk_risk_code UNIQUE (TENANT_ID, SCENARIO_ID, RISK_CODE)
);

-- 41. CONTROL_MASTER
CREATE TABLE CONTROL_MASTER (
    CONTROL_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    CONTROL_CODE VARCHAR(50) NOT NULL,
    CONTROL_NAME VARCHAR(200) NOT NULL,
    CONTROL_TYPE VARCHAR(12) CHECK (CONTROL_TYPE IN ('Preventive','Detective','Corrective')) NOT NULL,
    CONTROL_MODE VARCHAR(16) CHECK (CONTROL_MODE IN ('Manual','Automated','Semi_Automated')) DEFAULT 'Manual',
    IS_KEY_CONTROL BOOLEAN DEFAULT FALSE,
    CONTROL_TASK_ID BIGINT NULL,
    CONTROL_OWNER_JOB_ID BIGINT NULL,
    CONTROL_TESTER_JOB_ID BIGINT NULL,
    TESTING_FREQUENCY VARCHAR(40),
    EVIDENCE_REQUIRED TEXT,
    VALID_FROM DATE,
    VALID_TO DATE,
    STATUS VARCHAR(14) CHECK (STATUS IN ('Active','Deprecated','Under_Review')) DEFAULT 'Active',
    CONSTRAINT uk_ctrl_code UNIQUE (TENANT_ID, SCENARIO_ID, CONTROL_CODE)
);

-- 42. RISK_CONTROL_LINK
