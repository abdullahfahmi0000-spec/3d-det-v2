-- 95. DIDACTIC_OBSERVATION
CREATE TABLE DIDACTIC_OBSERVATION (
    DIDACTIC_OBSERVATION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    ENROLLMENT_ID BIGINT NOT NULL,
    STUDENT_WORKSPACE_ID BIGINT NULL,
    SOURCE_TYPE VARCHAR(20) NOT NULL CHECK (SOURCE_TYPE IN ('Navigation','Modification','Simulator_Cycle','Reset','Quiz','Assignment','Tutor_Interaction')),
    OBSERVED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    OBJECT_TYPE VARCHAR(50) NULL,
    OBJECT_ID BIGINT NULL,
    TUTOR_HELP_LEVEL VARCHAR(10) NULL CHECK (TUTOR_HELP_LEVEL IN ('Explain','Guide','Verify')),
    DETAIL_JSON JSONB NULL,
    EXCLUDED_FROM_ASSESSMENT BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_do_tutor_excluded CHECK (SOURCE_TYPE <> 'Tutor_Interaction' OR EXCLUDED_FROM_ASSESSMENT = TRUE),
    CONSTRAINT chk_do_tutor_level CHECK (SOURCE_TYPE <> 'Tutor_Interaction' OR TUTOR_HELP_LEVEL IS NOT NULL)
);

-- 96. ASSESSMENT_RECORD
CREATE TABLE ASSESSMENT_RECORD (
    ASSESSMENT_RECORD_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    ENROLLMENT_ID BIGINT NOT NULL,
    INSTRUMENT_TYPE VARCHAR(25) NOT NULL CHECK (INSTRUMENT_TYPE IN ('Quiz','Assignment','BPR_Simulation','Benchmark_Comparison','Trace_Analysis')),
    INSTRUMENT_REF BIGINT NULL,
    LMS_RUBRIC_ID BIGINT NULL,
    LMS_GRADE_CATEGORY_ID BIGINT NULL,
-- evidence fields (AI-writable)
    EVIDENCE_JSON JSONB NULL,
    EVIDENCE_OBSERVATION_REFS JSONB NULL,
    EVIDENCE_FLAG VARCHAR(25) NULL CHECK (EVIDENCE_FLAG IN ('Conflicting_Evidence','Anomalous_Distance')),
    EVIDENCE_WRITTEN_BY VARCHAR(10) NULL CHECK (EVIDENCE_WRITTEN_BY IN ('AI','Professor')),
    EVIDENCE_AT TIMESTAMP NULL,
-- judgement fields (professor-only)
    JUDGEMENT_GRADE DECIMAL(6,2) NULL,
    JUDGEMENT_SCALE_MAX DECIMAL(6,2) NULL,
    JUDGEMENT_PROFESSOR_PERSON_ID BIGINT NULL,
    JUDGEMENT_AT TIMESTAMP NULL,
    JUDGEMENT_NOTE TEXT NULL,
    CONSTRAINT chk_ar_judgement_complete CHECK (
 (JUDGEMENT_GRADE IS NULL AND JUDGEMENT_PROFESSOR_PERSON_ID IS NULL AND JUDGEMENT_AT IS NULL)
 OR (JUDGEMENT_GRADE IS NOT NULL AND JUDGEMENT_PROFESSOR_PERSON_ID IS NOT NULL AND JUDGEMENT_AT IS NOT NULL AND JUDGEMENT_SCALE_MAX IS NOT NULL)),
    CONSTRAINT chk_ar_grade_range CHECK (JUDGEMENT_GRADE IS NULL OR (JUDGEMENT_GRADE >= 0 AND JUDGEMENT_GRADE <= JUDGEMENT_SCALE_MAX))
);
