-- 85. ACADEMIC_UNIT
CREATE TABLE ACADEMIC_UNIT (
    ACADEMIC_UNIT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    UNIT_CODE VARCHAR(50) NOT NULL,
    UNIT_NAME VARCHAR(255) NOT NULL,
    UNIT_TYPE VARCHAR(20) NOT NULL CHECK (UNIT_TYPE IN ('Campus','Faculty','Department')),
