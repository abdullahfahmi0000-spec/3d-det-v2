-- 97. LMS_RUBRIC
CREATE TABLE LMS_RUBRIC (
    LMS_RUBRIC_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL,
    SCENARIO_ID BIGINT NOT NULL DEFAULT 0,
    COURSE_ID BIGINT NOT NULL,
    RUBRIC_CODE VARCHAR(50) NOT NULL,
    RUBRIC_NAME VARCHAR(255) NOT NULL,
    CREATED_BY_PERSON_ID BIGINT NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'Draft' CHECK (STATUS IN ('Draft','Active','Retired')),
    CONSTRAINT uk_rub UNIQUE (COURSE_ID, RUBRIC_CODE)
);

